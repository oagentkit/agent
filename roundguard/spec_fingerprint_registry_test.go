// TestSpecFingerprintRejectsHalfWidthColonProse 反向验证（终审复审 F2 ①）：判据小节里
// 加一条**半角冒号**的散文判据 ⇒ 必须变红。
//
// 为什么必须钉这条：散文判据腿原先只认**全角**冒号 ⇒ spec 里把同一句判据改写成
// 半角（Markdown 里两种都常见）时，这条腿**认不出来** ⇒ 判据不响——规则在、报告照常、
// 就是判不到（本仓反复强调的最贵失效形态）。
//
// 只写「好实现能过」的用例，一个把正则改回「只认全角」的错实现照样全过 ⇒ 这条是
// 「坏实现会红」的证据位。
func TestSpecFingerprintRejectsHalfWidthColonProse(t *testing.T) {
	injected := "\n**注入的散文判据**: 这是用半角冒号写的判据。\n"
	inj := injectIntoCriterionSection(readSpecText(t), "7.3", injected)
	fp := deriveSpecFingerprint(inj)
	// ① **派生面必须看见**这条半角冒号判据 —— 这一条才是「形态无关」的直接证据。
	//
	// ⚠️ 为什么不能只判「有没有违规」：旧实现下**也有**违规（登记面比派生面大）
	// ⇒ 只判「有违规」的用例在坏实现下**照样绿** ⇒ 那是假绿。
	// ⇒ 必须断言「注入的那一条**被派生出来了**」。
	if !slices.Contains(fp.prose["7.3"], "注入的散文判据") {
		t.Fatalf("半角冒号的散文判据没被派生出来（§7.3 实得 %v）⇒ 形态敏感还在", fp.prose["7.3"])
	}
	// ② 判定面必须因此变红（与登记面不一致）。
	v := fp.violations()
	found := false
	for _, s := range v {
		if strings.Contains(s, "§7.3") && strings.Contains(s, "散文判据") {
			found = true
		}
	}
	if !found {
		t.Errorf("未报出「§7.3 的散文判据与登记面不一致」，实际报出：%v", v)
	}
}

// TestSpecFingerprintRejectsProseInNonCriterionSection 反向验证（终审复审 F2 ②）：
// 往**不是判据面小节**的 `### ` 小节（§9.1）里加一条散文判据 ⇒ 必须变红。
//
// 为什么必须钉这条：散文判据腿原先只覆盖「矩阵要逐条钉的那 14 个判据面小节」
// ⇒ §9.x 这类小节里的散文判据**不在判定面内** ⇒ 在那里新加一条判据时，这条闸
// **一声不响**。§9.1 是**登记表与门禁**那一节——新判据最可能落在这里 ⇒ 选它当
// 注入点。
//
// 只写「好实现能过」的用例，一个把覆盖面缩回 14 个小节的错实现照样全过 ⇒ 这条是
// 「坏实现会红」的证据位。
func TestSpecFingerprintRejectsProseInNonCriterionSection(t *testing.T) {
	injected := "\n**注入的散文判据**：这是一条加在非判据面小节里的判据。\n"
	inj := injectIntoCriterionSection(readSpecText(t), "9.1", injected)
	fp := deriveSpecFingerprint(inj)
	// ① **派生面必须看见**非判据面小节里的散文判据 —— 这一条才是「覆盖全部
	// `### ` 小节」的直接证据（同上：只判「有没有违规」在坏实现下会假绿）。
	if !slices.Contains(fp.prose["9.1"], "注入的散文判据") {
		t.Fatalf("非判据面小节 §9.1 的散文判据没被派生出来（实得 %v）⇒ 覆盖面不全还在", fp.prose["9.1"])
	}
	// ② 判定面必须因此变红（与登记面不一致）。
	v := fp.violations()
	found := false
	for _, s := range v {
		if strings.Contains(s, "§9.1") && strings.Contains(s, "散文判据") {
			found = true
		}
	}
	if !found {
		t.Errorf("未报出「§9.1 的散文判据与登记面不一致」，实际报出：%v", v)
	}
}
